"""Generate privacy records from the personal-data registry.

The registry drives export, erasure, retention, and these documents. Keeping the
renderer deterministic lets CI reject a schema decision that was not committed with
its corresponding human-readable record.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path

from procuresignal.privacy.inventory import (
    INVENTORY,
    PersonalDataTable,
    SubjectLink,
    unregistered_tables,
)

ROOT = Path(__file__).resolve().parents[1]
INVENTORY_PATH = ROOT / "docs" / "personal-data-inventory.md"
RECORD_PATH = ROOT / "docs" / "processing-record.md"

GENERATED_NOTICE = "<!-- Generated by scripts/generate_privacy_docs.py. Do not edit by hand. -->"


def _cell(value: object) -> str:
    """Render registry prose safely inside a Markdown table cell."""

    return " ".join(str(value).split()).replace("|", "\\|")


def _subject_link(entry: PersonalDataTable) -> str:
    if entry.link is SubjectLink.NONE:
        return "None declared"
    return f"{entry.link.value} through {entry.link_column}"


def _retention(entry: PersonalDataTable) -> str:
    if entry.retention_days is None:
        return "No automatic expiry"
    return f"{entry.retention_days} days from {entry.retention_column}"


def render_personal_data_inventory(entries: Sequence[PersonalDataTable]) -> str:
    """Return the operational data inventory as deterministic Markdown."""

    lines = [
        "# Personal data inventory",
        "",
        GENERATED_NOTICE,
        "",
        "This inventory is generated from the registry used by subject access, erasure,",
        "and retention. A row with no subject link is an explicit no-personal-data",
        "decision, not an unreviewed omission.",
        "",
        "| Table | Subject link | Purpose | Erasure | Retention | Note |",
        "|---|---|---|---|---|---|",
    ]
    for entry in sorted(entries, key=lambda item: item.table):
        lines.append(
            "| "
            + " | ".join(
                (
                    f"`{_cell(entry.table)}`",
                    _cell(_subject_link(entry)),
                    _cell(entry.purpose),
                    _cell(entry.erasure.value),
                    _cell(_retention(entry)),
                    _cell(entry.retention_note or "—"),
                )
            )
            + " |"
        )
    return "\n".join(lines) + "\n"


def render_processing_record(entries: Sequence[PersonalDataTable]) -> str:
    """Return the engineering-backed GDPR Article 30 working record."""

    lines = [
        "# Record of processing activities",
        "",
        GENERATED_NOTICE,
        "",
        "This is the technical record of processing generated from ProcureSignal's",
        "runtime privacy registry. It is a working Article 30 record, not legal advice.",
        "",
        "## Controller and legal review",
        "",
        "- Controller identity and contact details: **OWNER INPUT REQUIRED**.",
        "- Data Protection Officer or representative, if applicable: **OWNER INPUT REQUIRED**.",
        "- Lawful basis for each processing purpose: **OWNER INPUT REQUIRED**.",
        "- Categories of recipients and international transfers: **OWNER INPUT REQUIRED**.",
        "",
        "## Technical and organisational measures",
        "",
        "Tenant-scoped authorization, role checks, encrypted transport, secret-file",
        "resolution, append-only audit evidence, bounded retention, subject export and",
        "erasure workflows, dependency scanning, rate limiting, and monitored background",
        "processing are implemented in the application. Deployment-specific controls",
        "must be reviewed for the selected hosting environment.",
        "",
        "## Processing activities",
        "",
        "| Table | Data-subject link | Purpose | Erasure action | Retention | Legal / operational note |",
        "|---|---|---|---|---|---|",
    ]
    for entry in sorted(entries, key=lambda item: item.table):
        lines.append(
            "| "
            + " | ".join(
                (
                    f"`{_cell(entry.table)}`",
                    _cell(_subject_link(entry)),
                    _cell(entry.purpose),
                    _cell(entry.erasure.value),
                    _cell(_retention(entry)),
                    _cell(entry.retention_note or "—"),
                )
            )
            + " |"
        )
    return "\n".join(lines) + "\n"


def generated_documents(
    entries: Sequence[PersonalDataTable] = INVENTORY,
) -> dict[Path, str]:
    """Return every generated path and its expected content."""

    names = [entry.table for entry in entries]
    if len(names) != len(set(names)):
        raise RuntimeError("privacy registry contains duplicate table names")

    missing = unregistered_tables()
    if missing:
        raise RuntimeError(
            "privacy registry is missing schema tables: " + ", ".join(sorted(missing))
        )

    return {
        INVENTORY_PATH: render_personal_data_inventory(entries),
        RECORD_PATH: render_processing_record(entries),
    }


def check_documents(expected: Mapping[Path, str]) -> list[Path]:
    """Return missing or stale paths without modifying the working tree."""

    return sorted(
        path
        for path, content in expected.items()
        if not path.is_file() or path.read_text(encoding="utf-8") != content
    )


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="report stale generated records instead of writing them",
    )
    args = parser.parse_args(argv)
    documents = generated_documents()

    if args.check:
        stale = check_documents(documents)
        for path in stale:
            print(f"stale generated privacy record: {path.relative_to(ROOT)}", file=sys.stderr)
        return 1 if stale else 0

    for path, content in documents.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
